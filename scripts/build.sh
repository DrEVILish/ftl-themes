#!/usr/bin/env bash
# Builds dist/<theme>.css bundles (reset + core + theme [+ chrome]) and
# dist/themes.json, the machine-readable index consuming apps and
# components.html both read so nobody has to hardcode or scrape the theme list.
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"

mkdir -p dist
# Start from an empty dist/: a bundle for a theme that was removed or
# renamed would otherwise stay on disk, stay committed (the dist-sync check
# only sees files a build changes), and keep feeding themes.json's version.
rm -f dist/*.css dist/themes.json

# Bundled CSS sits one directory deeper than the theme sources it's built
# from, so relative url() references (the LCARS @font-face) would 404 from
# dist/. Apps serve assets/ next to dist/, so rewrite to ../assets/.
# v5 component groups (core/components/*.css), in name order, after core.css
# so they can build on its components and tokens.
cat_components() { for f in core/components/*.css; do [ -f "$f" ] && cat "$f"; done; return 0; }
rewrite_urls() { sed 's#url("assets/#url("../assets/#g; s#url(assets/#url(../assets/#g; s/[[:space:]]*$//'; }
# CSS-only selection: .is-active / [aria-selected="true"] also match an item
# whose own radio or checkbox is checked (scripts/radio_state.py).
radio_state() { python3 "$root/scripts/radio_state.py"; }
# html[data-motion="always"]: every motion block also applies on unattended
# screens that report reduced motion (scripts/motion_always.py).
motion_always() { python3 "$root/scripts/motion_always.py"; }

# core/reset.css + core.css alone, with no theme and no layout
# shell — for an app that wants the --* token contract and component
# structure but supplies its own palette (color-only adoption), or that
# will never adopt the .app shell. See CONTRACT.md "Color-only
# adoption". No components are USABLE until a theme (or the app itself)
# defines the tokens they read — this file supplies structure, not look.
{
  echo "/* ftl-themes: core structure only (reset + components), no theme, no"
  echo " * app shell. See CONTRACT.md \"Color-only adoption\" — components need"
  echo " * a theme (or your own --* values) layered on top before they"
  echo " * have a look at all. Build identity lives in dist/themes.json, not"
  echo " * here, so this file's content stays stable across rebuilds of the"
  echo " * same source and doesn't spuriously fail the dist-sync check. */"
  echo "@layer ui {"
  cat core/reset.css
  cat core/core.css
  cat_components
  cat core/cursors.css
  echo "}"
} | rewrite_urls | radio_state | motion_always > dist/core.css
echo "built dist/core.css"

for dir in themes/*/; do
  name="$(basename "$dir")"
  src="themes/${name}/theme.css"
  # Same rule as build_bundles.py/build_manifest.py: a directory without a
  # theme.css is not a theme (a half-scaffolded or leftover folder).
  [ -f "$src" ] || continue
  out="dist/${name}.css"
  {
    echo "/* ftl-themes: ${name} — generated by scripts/build.sh."
    echo " * Do not edit; edit themes/${name}/theme.css instead. */"
    # Everything sits in one cascade layer, \`ui\`: with the class/token prefix
    # gone in v4, the layer is what keeps an app's own unlayered CSS (and any
    # framework's) in charge of a name collision. See CONTRACT.md "Cascade layers".
    echo "@layer ui {"
    cat core/reset.css
    cat core/core.css
    cat_components
    cat core/layout.css
    cat core/cursors.css
    python3 scripts/theme_inheritance.py "$name"
    echo "}"
  } | rewrite_urls | radio_state | motion_always > "$out"
  echo "built $out"
done

# Manifest (including per-theme scheme/luminance and build identity) is
# generated in Python — its derivations must match what check.py re-derives,
# and check.py imports them from this script rather than re-implementing.
python3 scripts/build_bundles.py >/dev/null
python3 scripts/build_manifest.py
python3 scripts/build_component_index.py

# Per-theme icon sprites: dist/icons/<slug>.svg merges the generic sprite
# (assets/icons/icons.svg) with that theme's own themes/<slug>/icons.svg
# overrides, if any — see scripts/build_icons.py and CONTRACT.md "Icon
# system". Every theme gets a merged sprite generated for it, even one
# with no overrides, so the reference path is always valid.
python3 scripts/build_icons.py

# Themed transactional emails: tokens resolved to literal colours in
# table-based, inline-styled HTML + plain text (dist/email/<slug>/).
python3 scripts/build_emails.py

# Per-theme favicons and app icons (SVG + PNG) — see scripts/build_favicons.py.
python3 scripts/build_favicons.py
